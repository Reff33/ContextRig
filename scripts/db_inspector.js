/**
 * ContextRig Database Schema Inspector Utility
 * Inspects local database schemas (SQLite, .env connection profiles)
 * and generates a concise markdown summary for AI agents.
 * 
 * Usage: node tools/db_inspector.js [DB_FILE_OR_PATH]
 */
import fs from 'node:fs/promises';
import path from 'node:path';
import { existsSync } from 'node:fs';

// Try loading native node:sqlite (available in Node 22+)
let DatabaseSync = null;
try {
  const sqliteModule = await import('node:sqlite');
  DatabaseSync = sqliteModule.DatabaseSync;
} catch {
  // node:sqlite not supported in older node runtimes
}

/**
 * Searches for common SQLite database files in a project.
 * @param {string} rootDir
 * @returns {Promise<string|null>}
 */
async function findSqliteFile(rootDir = '.') {
  const candidates = [
    'database/database.sqlite',
    'database.sqlite',
    'db.sqlite',
    'db.sqlite3',
    'app.db',
    'data.db',
    'storage/database.sqlite'
  ];

  for (const c of candidates) {
    const full = path.resolve(rootDir, c);
    if (existsSync(full)) {
      return full;
    }
  }

  // Scan root for any .sqlite or .db file
  try {
    const files = await fs.readdir(rootDir);
    for (const file of files) {
      if (file.endsWith('.sqlite') || file.endsWith('.sqlite3') || file.endsWith('.db')) {
        return path.resolve(rootDir, file);
      }
    }
  } catch {
    // Ignore scan errors
  }

  return null;
}

/**
 * Parses a simple .env file to extract database configuration hints.
 * @param {string} rootDir
 * @returns {Promise<Object>}
 */
async function parseEnvDatabaseConfig(rootDir = '.') {
  const envPath = path.resolve(rootDir, '.env');
  const config = {};

  if (!existsSync(envPath)) return config;

  try {
    const content = await fs.readFile(envPath, 'utf8');
    const lines = content.split(/\r?\n/);
    for (const line of lines) {
      const trimmed = line.trim();
      if (!trimmed || trimmed.startsWith('#')) continue;
      const idx = trimmed.indexOf('=');
      if (idx !== -1) {
        const key = trimmed.slice(0, idx).trim();
        const val = trimmed.slice(idx + 1).trim().replace(/^['"]|['"]$/g, '');
        if (key.startsWith('DB_')) {
          config[key] = val;
        }
      }
    }
  } catch {
    // Ignore .env read errors
  }

  return config;
}

/**
 * Inspects a SQLite database using native node:sqlite.
 * @param {string} dbPath
 * @returns {Object}
 */
function inspectSqlite(dbPath) {
  if (!DatabaseSync) {
    return {
      error: 'Native node:sqlite is not supported in this Node.js runtime. Please upgrade to Node 22+.'
    };
  }

  const db = new DatabaseSync(dbPath, { open: true, readOnly: true });
  const tablesStmt = db.prepare(`
    SELECT name FROM sqlite_master 
    WHERE type='table' AND name NOT LIKE 'sqlite_%'
    ORDER BY name
  `);
  const tables = tablesStmt.all();

  const schema = {};
  for (const table of tables) {
    const tableName = table.name;
    const columnsStmt = db.prepare(`PRAGMA table_info("${tableName}")`);
    const columns = columnsStmt.all();

    schema[tableName] = columns.map((col) => ({
      name: col.name,
      type: col.type || 'TEXT',
      notnull: Boolean(col.notnull),
      pk: Boolean(col.pk)
    }));
  }

  db.close();
  return { type: 'sqlite', file: dbPath, schema };
}

/**
 * Formats inspected schema into a clean markdown document.
 * @param {Object} inspectedData
 * @param {Object} envConfig
 * @returns {string}
 */
function formatSchemaMarkdown(inspectedData, envConfig) {
  const lines = [
    '# Database Schema Context',
    '',
    `*Generated by ContextRig DB Inspector on ${new Date().toISOString()}*`,
    ''
  ];

  if (Object.keys(envConfig).length > 0) {
    lines.push('## Connection Profile (.env)');
    for (const [k, v] of Object.entries(envConfig)) {
      if (k === 'DB_PASSWORD') {
        lines.push(`- **${k}**: ********`);
      } else {
        lines.push(`- **${k}**: \`${v}\``);
      }
    }
    lines.push('');
  }

  if (inspectedData.error) {
    lines.push(`> [!WARNING]\n> ${inspectedData.error}`);
    return lines.join('\n');
  }

  if (inspectedData.schema) {
    lines.push('## Tables & Columns');
    const tableNames = Object.keys(inspectedData.schema);
    if (tableNames.length === 0) {
      lines.push('No user tables found in database.');
    } else {
      for (const tName of tableNames) {
        lines.push(`### \`${tName}\``);
        lines.push('| Column | Type | Primary Key | Nullable |');
        lines.push('| :--- | :--- | :---: | :---: |');
        for (const col of inspectedData.schema[tName]) {
          lines.push(
            `| \`${col.name}\` | ${col.type} | ${col.pk ? 'Yes' : 'No'} | ${col.notnull ? 'No' : 'Yes'} |`
          );
        }
        lines.push('');
      }
    }
  }

  return lines.join('\n');
}

async function main() {
  const targetArg = process.argv[2];
  const rootDir = process.cwd();

  console.log('> Inspecting database schema...');

  const envConfig = await parseEnvDatabaseConfig(rootDir);
  let dbFile = targetArg ? path.resolve(rootDir, targetArg) : await findSqliteFile(rootDir);

  let inspectedResult = {};
  if (dbFile && existsSync(dbFile)) {
    console.log(`> Found SQLite database: ${path.relative(rootDir, dbFile)}`);
    try {
      inspectedResult = inspectSqlite(dbFile);
    } catch (err) {
      inspectedResult = { error: `Failed to inspect SQLite database: ${err.message}` };
    }
  } else {
    inspectedResult = {
      error: 'No local SQLite database file detected. Inspecting .env configuration only.'
    };
  }

  const markdownContent = formatSchemaMarkdown(inspectedResult, envConfig);
  const outDir = path.resolve(rootDir, 'docs');
  await fs.mkdir(outDir, { recursive: true });

  const outFilePath = path.join(outDir, 'db_schema.md');
  await fs.writeFile(outFilePath, markdownContent, 'utf8');

  console.log(`[OK] Schema context written to: ${outFilePath}`);
  console.log('\n--- Schema Preview ---');
  console.log(markdownContent);
}

main().catch((err) => {
  console.error(`Error: ${err.message}`);
  process.exit(1);
});

